func writeTuner(c *saa7164usb.Client, reg, val byte) error {
	return c.I2CWrite(TunerUnit, reg, []byte{val, 0xfe})
}

func writeDemod(c *saa7164usb.Client, reg, val byte) error {
	return c.I2CWrite(DemodUnit, reg, []byte{val})
}

// Init は GPIO 起床と Saigawa チューナー・復調器の初期レジスタ設定を行う。
// 未初期化状態で I2CRead(TunerUnit, 0x00) を行うと I2C がロックするため、必ず最初にこれを実行する。
func Init(c *saa7164usb.Client) error {
	if err := c.SetGPIO(DemodUnit, 0, 0); err != nil {
		return fmt.Errorf("GPIO リセット失敗: %w", err)
	}
	time.Sleep(10 * time.Millisecond)
	if err := c.SetGPIO(DemodUnit, 0, 1); err != nil {
		return fmt.Errorf("GPIO 解除失敗: %w", err)
	}
	time.Sleep(2000 * time.Millisecond)

	_ = c.I2CWrite(TunerUnit, 0xff, []byte{0xff})
	if err := writeTuner(c, 0x09, 0xb1); err != nil {
		return fmt.Errorf("tuner 0x09 失敗: %w", err)
	}
	time.Sleep(1 * time.Millisecond)
	for _, rv := range tunerInitRegs {
		if err := writeTuner(c, rv.reg, rv.val); err != nil {
			return fmt.Errorf("tuner 0x%02x 失敗: %w", rv.reg, err)
		}
	}
	for _, rv := range demodInitRegs {
		if err := writeDemod(c, rv.reg, rv.val); err != nil {
			return fmt.Errorf("demod 0x%02x 失敗: %w", rv.reg, err)
		}
	}
	return nil
}

// LookupFreq は周波数（Hz）に対応するチューナーレジスタ表のエントリを返す。
func LookupFreq(freqHz uint32) (freqEntry, error) {
	if freqHz < 90_000_000 || freqHz > 773_000_000 {
		return freqEntry{}, fmt.Errorf("対象外の周波数: %d Hz", freqHz)
	}
	for _, e := range freqTable {
		if freqHz < e.freqHz+3_000_000 {
			return e, nil
		}
	}
	return freqTable[len(freqTable)-1], nil
}

// TuneISDBT は指定周波数（Hz）に同調し、ロック待ちを行う。
func TuneISDBT(c *saa7164usb.Client, freqHz uint32) (bool, error) {
	ent, err := LookupFreq(freqHz)
	if err != nil {
		return false, err
	}
	header := []regVal{
		{0xa8, 0xd2}, {0x95, 0x03}, {0x09, 0xb1}, {0x88, 0x7e}, {0x8a, 0x38},
	}
	for _, rv := range header {
		if err := writeTuner(c, rv.reg, rv.val); err != nil {
			return false, err
		}
	}
	for i, addr := range freqRegAddrs {
		if err := writeTuner(c, addr, ent.regs[i]); err != nil {
			return false, err
		}
	}
	if err := writeTuner(c, 0x09, 0xf3); err != nil {
		return false, err
	}
	time.Sleep(30 * time.Millisecond)
	if err := writeTuner(c, 0x88, 0xfe); err != nil {
		return false, err
	}
	if err := writeTuner(c, 0x09, 0xf3); err != nil {
		return false, err
	}
	if err := writeDemod(c, 0x01, 0x40); err != nil {
		return false, err
	}

	for i := 0; i < 20; i++ {
		time.Sleep(150 * time.Millisecond)
		_, _, locked, err := ReadLock(c)
		if err == nil && locked {
			return true, nil
		}
	}
	return false, nil
}

// ReadLock は復調器の状態レジスタ（0x80, 0xb0）とロック可否を返す。
func ReadLock(c *saa7164usb.Client) (r80, rB0 byte, locked bool, err error) {
	v1, err := c.I2CRead(DemodUnit, 0x80, 1)
	if err != nil {
		return 0, 0, false, err
	}
	v2, err := c.I2CRead(DemodUnit, 0xb0, 1)
	if err != nil {
		return 0, 0, false, err
	}
	r80, rB0 = v1[0], v2[0]
	locked = (r80&0x28) == 0 && (rB0&0x0f) >= 8
	return r80, rB0, locked, nil
}

// ReadSignalStrength は復調器の電界強度レジスタ（0x94）を返す。
func ReadSignalStrength(c *saa7164usb.Client) (byte, error) {
	v, err := c.I2CRead(DemodUnit, 0x94, 1)
	if err != nil {
		return 0, err
	}
	return v[0], nil
}
